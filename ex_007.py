# Desenvolva um programa que leia as duas notas
# de um aluno, calcule e mostra a sua média.

n1 = float(input('Digite a primeira nota: '))
n2 = float(input('Digite a segunda nota: '))
media = (n1 + n2) / 2

print(f'A primeira nota foi "{n1}", a segunda nota foi "{n2}"')
print(f'Logo, a média foi "{media}".')
